  0x00, 0x00, 0x00, 0x1F, 0x15, 0xC4, 0x89, 0x00, 0x00, 0x00, 0x0A, 0x49, 0x44,
  0x41, 0x54, 0x78, 0x9C, 0x63, 0x00, 0x01, 0x00, 0x00, 0x05, 0x00, 0x01, 0x0D,
  0x0A, 0x2D, 0xB4, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4E, 0x44, 0xAE, 0x42,
  0x60, 0x82,
]);

void main() {
  setUp(() {
    HttpOverrides.global = TestHttpOverrides();
    GoogleFonts.config.allowRuntimeFetching = false;
  });

  tearDown(() {
    HttpOverrides.global = null;
  });

  testWidgets('Webee Florist Landing Page Web Smoke Test', (WidgetTester tester) async {
    tester.view.physicalSize = const Size(1280, 900);
    tester.view.devicePixelRatio = 1.0;
    addTearDown(() {
      tester.view.resetPhysicalSize();
      tester.view.resetDevicePixelRatio();
    });

    await tester.pumpWidget(
      ProviderScope(
        overrides: [
          autentikasiProvider.overrideWith((ref) => MockNotifierAutentikasi()),
          daftarKategoriProvider.overrideWith((ref) => Future.value([])),
          daftarProdukProvider.overrideWith((ref) => Future.value([])),
        ],
        child: const AplikasiWebeeFlorist(),
      ),
    );
    await tester.pumpAndSettle();

    // Verifikasi elemen utama Landing Page hadir
    expect(
      find.text("L'Art des Fleurs — Keindahan Rangkaian Bunga Klasik Romantis"),
      findsOneWidget,
    );
    expect(find.text('Jelajahi Koleksi Bunga'), findsOneWidget);
  });
}
